"""Build small startup previews. Original artwork stays untouched."""
from pathlib import Path
from PIL import Image
import base64, io, json
root = Path(__file__).resolve().parents[1]
previews = {}
for path in sorted((root / 'web/merge-sprites').rglob('*.png')):
    image = Image.open(path).convert('RGBA')
    image.thumbnail((128, 128), Image.Resampling.LANCZOS)
    buffer = io.BytesIO()
    image.save(buffer, format='WEBP', quality=85, method=4)
    previews[path.relative_to(root / 'web').as_posix()] = 'data:image/webp;base64,' + base64.b64encode(buffer.getvalue()).decode('ascii')
output = root / 'web/merge-previews.js'
output.write_text('// Generated by tools/build_merge_previews.py; temporary previews, replaced by native PNGs.\nwindow.MergePreviews=' + json.dumps(previews, separators=(',', ':')) + ';\n', encoding='utf-8')
print(f'{len(previews)} embedded previews: {output.stat().st_size:,} bytes')
